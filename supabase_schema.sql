-- ==============================================================================
-- Supabase Schema for Zero-Update Hotel Price Scraper (hs_ namespace)
-- ==============================================================================

-- 1. App Logs Table (Centralized logging sink for WARNING, ERROR, CRITICAL)
CREATE TABLE IF NOT EXISTS public.hs_app_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id TEXT NOT NULL,
    level TEXT NOT NULL,
    module TEXT,
    message TEXT NOT NULL,
    traceback TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_hs_app_logs_level ON public.hs_app_logs(level);
CREATE INDEX IF NOT EXISTS idx_hs_app_logs_created_at ON public.hs_app_logs(created_at DESC);

-- Enable RLS & simple insert policy
ALTER TABLE public.hs_app_logs ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow anon insert logs" ON public.hs_app_logs FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon read logs" ON public.hs_app_logs FOR SELECT USING (true);


-- 2. Target Hotels Table (Runtime list of hotels to scrape)
CREATE TABLE IF NOT EXISTS public.hs_target_hotels (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    booking_url TEXT NOT NULL,
    direct_url TEXT NOT NULL,
    rooms_catalog_url TEXT,
    direct_booking_engine TEXT DEFAULT 'generic',
    matching_rules JSONB DEFAULT '{}'::jsonb,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.hs_target_hotels ADD COLUMN IF NOT EXISTS rooms_catalog_url TEXT;
ALTER TABLE public.hs_target_hotels ADD COLUMN IF NOT EXISTS matching_rules JSONB DEFAULT '{}'::jsonb;

ALTER TABLE public.hs_target_hotels ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow anon read hs_target_hotels" ON public.hs_target_hotels FOR SELECT USING (true);

-- 2b. Room Mappings Table (Pre-computed N:1 room catalog mappings)
CREATE TABLE IF NOT EXISTS public."hs-room_mappings" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id TEXT NOT NULL,
    capacity_group TEXT NOT NULL,
    direct_room_pattern TEXT NOT NULL,
    booking_room_name TEXT,
    match_score INTEGER DEFAULT 0,
    is_exclusive_direct BOOLEAN DEFAULT FALSE,
    is_manual_override BOOLEAN DEFAULT FALSE,
    priority INTEGER DEFAULT 100,
    is_active BOOLEAN DEFAULT TRUE,
    last_synced_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (hotel_id, capacity_group, direct_room_pattern)
);

CREATE INDEX IF NOT EXISTS idx_hs_room_mappings_hotel_active
    ON public."hs-room_mappings"(hotel_id, is_active, priority);

ALTER TABLE public."hs-room_mappings" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow anon read hs-room_mappings" ON public."hs-room_mappings" FOR SELECT USING (true);
CREATE POLICY "Allow anon upsert hs-room_mappings" ON public."hs-room_mappings" FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon update hs-room_mappings" ON public."hs-room_mappings" FOR UPDATE USING (true);


-- 3. Scraping Configs Table (Zero-Update dynamic selectors, regexes, and rules)
CREATE TABLE IF NOT EXISTS public.hs_scraping_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    engine TEXT UNIQUE NOT NULL,
    rules JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.hs_scraping_configs ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow anon read hs_scraping_configs" ON public.hs_scraping_configs FOR SELECT USING (true);


